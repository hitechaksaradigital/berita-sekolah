create policy "Pengguna login mengunggah gambar"
  on storage.objects for insert
  to authenticated
  with check (bucket_id = 'news-images');

drop policy if exists "Pengguna login memperbarui gambar" on storage.objects;
create policy "Pengguna login memperbarui gambar"
  on storage.objects for update
  to authenticated
  using (bucket_id = 'news-images')
  with check (bucket_id = 'news-images');

drop policy if exists "Pengguna login menghapus gambar" on storage.objects;
create policy "Pengguna login menghapus gambar"
  on storage.objects for delete
  to authenticated
  using (bucket_id = 'news-images');

