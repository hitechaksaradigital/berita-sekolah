create extension if not exists pgcrypto;

-- ---------------------------------------------------------------------------
-- 2. Tabel
-- ---------------------------------------------------------------------------
create table if not exists public.profiles (
  id uuid primary key references auth.users (id) on delete cascade,
  full_name text not null default '',
  email text,
  role text not null default 'writer' check (role in ('admin', 'writer')),
  avatar_url text,
  created_at timestamptz not null default now()
);

create table if not exists public.categories (
  id bigint generated by default as identity primary key,
  name text not null unique,
  slug text not null unique,
  created_at timestamptz not null default now()
);

create table if not exists public.posts (
  id uuid primary key default gen_random_uuid(),
  title text not null,
  slug text not null unique,
  excerpt text,
  content text not null,
  thumbnail_url text,
  category_id bigint references public.categories (id) on delete set null,
  author_id uuid references public.profiles (id) on delete set null,
  status text not null default 'draft' check (status in ('draft', 'published', 'archived')),
  is_featured boolean not null default false,
  views_count integer not null default 0,
  published_at timestamptz,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create index if not exists posts_status_published_at_idx
  on public.posts (status, published_at desc);
create index if not exists posts_category_id_idx on public.posts (category_id);
create index if not exists posts_author_id_idx on public.posts (author_id);

-- ---------------------------------------------------------------------------
-- 3. Trigger
-- ---------------------------------------------------------------------------
create or replace function public.set_updated_at()
returns trigger
language plpgsql
as $$
begin
  new.updated_at = now();
  return new;
end;
$$;

drop trigger if exists posts_set_updated_at on public.posts;
create trigger posts_set_updated_at
  before update on public.posts
  for each row execute function public.set_updated_at();

-- Profil otomatis dibuat saat pengguna mendaftar via Supabase Auth.
-- Nama diambil dari metadata Email/OAuth bila tersedia; role default = writer.
create or replace function public.handle_new_user()
returns trigger
language plpgsql
security definer
set search_path = public
as $$
begin
  insert into public.profiles (id, full_name, email, role, avatar_url)
  values (
    new.id,
    coalesce(new.raw_user_meta_data ->> 'full_name', split_part(new.email, '@', 1), 'Pengguna Baru'),
    new.email,
    'writer',
    new.raw_user_meta_data ->> 'avatar_url'
  )
  on conflict (id) do nothing;
  return new;
end;
$$;

drop trigger if exists on_auth_user_created on auth.users;
create trigger on_auth_user_created
  after insert on auth.users
  for each row execute function public.handle_new_user();

-- ---------------------------------------------------------------------------
-- 4. Fungsi pembantu RLS
-- ---------------------------------------------------------------------------
-- SECURITY DEFINER sengaja dipakai agar pengecekan role tidak memicu
-- rekursi kebijakan RLS pada tabel profiles.
create or replace function public.is_admin()
returns boolean
language sql
stable
security definer
set search_path = public
as $$
  select exists (
    select 1 from public.profiles
    where id = auth.uid() and role = 'admin'
  );
$$;

revoke all on function public.is_admin() from public;
grant execute on function public.is_admin() to anon, authenticated;

-- ---------------------------------------------------------------------------
-- 5. Row Level Security
-- ---------------------------------------------------------------------------
alter table public.profiles enable row level security;
alter table public.categories enable row level security;
alter table public.posts enable row level security;

-- Profil pembaca berita ikut ditampilkan sebagai penulis pada kartu/artikel,
-- sehingga SELECT dibuka untuk publik. Kolom sensitif tidak disimpan di sini.
drop policy if exists "Profil dapat dibaca publik" on public.profiles;
create policy "Profil dapat dibaca publik"
  on public.profiles for select
  using (true);

drop policy if exists "Admin mengelola profil" on public.profiles;
create policy "Admin mengelola profil"
  on public.profiles for all
  using (public.is_admin())
  with check (public.is_admin());

drop policy if exists "Kategori dapat dibaca publik" on public.categories;
create policy "Kategori dapat dibaca publik"
  on public.categories for select
  using (true);

drop policy if exists "Admin mengelola kategori" on public.categories;
create policy "Admin mengelola kategori"
  on public.categories for all
  using (public.is_admin())
  with check (public.is_admin());

drop policy if exists "Berita published dapat dibaca publik" on public.posts;
create policy "Berita published dapat dibaca publik"
  on public.posts for select
  using (status = 'published' or auth.uid() is not null);

drop policy if exists "Penulis membuat berita draft" on public.posts;
create policy "Penulis membuat berita draft"
  on public.posts for insert
  to authenticated
  with check (
    (author_id = auth.uid() or public.is_admin())
    and (status <> 'published' or public.is_admin())
    and (is_featured = false or public.is_admin())
  );

drop policy if exists "Penulis mengedit beritanya sendiri" on public.posts;
create policy "Penulis mengedit beritanya sendiri"
  on public.posts for update
  to authenticated
  using (author_id = auth.uid() or public.is_admin())
  with check (
    (author_id = auth.uid() or public.is_admin())
    and (status <> 'published' or public.is_admin())
    and (is_featured = false or public.is_admin())
  );

drop policy if exists "Admin menghapus berita" on public.posts;
create policy "Admin menghapus berita"
  on public.posts for delete
  to authenticated
  using (public.is_admin());

-- ---------------------------------------------------------------------------
-- 6. RPC: menambah jumlah pembaca tanpa memberi izin UPDATE ke publik
-- ---------------------------------------------------------------------------
create or replace function public.increment_post_views(post_id uuid)
returns void
language plpgsql
security definer
set search_path = public
as $$
begin
  update public.posts
     set views_count = views_count + 1
   where id = post_id and status = 'published';
end;
$$;

revoke all on function public.increment_post_views(uuid) from public;
grant execute on function public.increment_post_views(uuid) to anon, authenticated;

